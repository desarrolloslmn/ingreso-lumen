-- Dashboard Portal - esquema inicial
-- Las tablas sensibles usan RLS sin policies para anon/authenticated.
-- El backend de Next.js accede con SUPABASE_SECRET_KEY y valida el JWT del usuario.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  name text not null default '',
  role text not null default 'user' check (role in ('admin', 'user')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create unique index if not exists profiles_email_lower_idx
  on public.profiles (lower(email));

create table if not exists public.dashboards (
  id text primary key,
  name text not null,
  description text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.dashboard_access (
  user_id uuid not null references public.profiles(id) on delete cascade,
  dashboard_id text not null references public.dashboards(id) on delete cascade,
  permission text not null check (permission in ('read', 'write')),
  created_at timestamptz not null default now(),
  primary key (user_id, dashboard_id)
);

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  actor_email text not null,
  action text not null,
  dashboard_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists audit_log_created_at_idx
  on public.audit_log (created_at desc);

create index if not exists audit_log_actor_id_idx
  on public.audit_log (actor_id);

create index if not exists audit_log_dashboard_id_idx
  on public.audit_log (dashboard_id);

create index if not exists dashboard_access_dashboard_id_idx
  on public.dashboard_access (dashboard_id);

