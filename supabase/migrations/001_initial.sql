create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, name, role, active, created_at)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(nullif(new.raw_user_meta_data ->> 'name', ''), split_part(coalesce(new.email, ''), '@', 1), 'Usuario'),
    'user',
    true,
    coalesce(new.created_at, now())
  )
  on conflict (id) do update
  set
    email = excluded.email,
    name = case
      when public.profiles.name = '' then excluded.name
      else public.profiles.name
    end;

  return new;
end;
$$;

-- Importa usuarios existentes sin otorgar privilegios administrativos automáticamente.
insert into public.profiles (id, email, name, role, active, created_at)
select
  u.id,
  coalesce(u.email, ''),
  coalesce(nullif(u.raw_user_meta_data ->> 'name', ''), split_part(coalesce(u.email, ''), '@', 1), 'Usuario'),
  'user',
  true,
  coalesce(u.created_at, now())
from auth.users u
on conflict (id) do nothing;

drop trigger if exists on_auth_user_created_dashboard_portal on auth.users;

create trigger on_auth_user_created_dashboard_portal
after insert on auth.users
for each row execute function public.handle_new_auth_user();

alter table public.profiles enable row level security;
alter table public.dashboards enable row level security;
alter table public.dashboard_access enable row level security;
alter table public.audit_log enable row level security;

-- Defensa en profundidad: el navegador (anon/authenticated) no accede directamente.
-- No se crean policies de lectura/escritura para estas tablas.
revoke all on table public.profiles from anon, authenticated;
revoke all on table public.dashboards from anon, authenticated;
revoke all on table public.dashboard_access from anon, authenticated;
revoke all on table public.audit_log from anon, authenticated;

-- El backend utiliza la clave privada de Supabase, que representa el rol service_role.
grant usage on schema public to service_role;
grant select, insert, update, delete on table public.profiles to service_role;
grant select, insert, update, delete on table public.dashboards to service_role;
grant select, insert, update, delete on table public.dashboard_access to service_role;
grant select, insert, update, delete on table public.audit_log to service_role;
grant usage, select on all sequences in schema public to service_role;
