-- Dashboard Portal - versión estática para GitHub Pages
-- Ejecutar en Supabase SQL Editor.
-- Esta migración permite que la SPA estática consulte Supabase directamente con RLS.
-- No requiere service_role en el navegador y no almacena secretos.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  name text not null default '',
  role text not null default 'user' check (role in ('admin', 'user')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.dashboards (
  id text primary key,
  name text not null,
  description text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.dashboard_access (
  user_id uuid not null references public.profiles(id) on delete cascade,
  dashboard_id text not null references public.dashboards(id) on delete cascade,
  permission text not null check (permission in ('read', 'write')),
  created_at timestamptz not null default now(),
  primary key (user_id, dashboard_id)
);

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  actor_email text,
  action text not null,
  dashboard_id text references public.dashboards(id) on delete set null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

